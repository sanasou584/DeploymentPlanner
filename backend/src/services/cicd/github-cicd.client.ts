
import { ConflictError } from '../../domain/errors/index.js';

interface GitHubRef {
  object: {
    sha: string;
  };
}

interface GitHubPullRequest {
  html_url: string;
  number: number;
}

export interface GitHubCicdFile {
  path: string;
  content: string;
}

export interface CreateWorkflowPullRequestInput {
  owner: string;
  repository: string;
  baseBranch: string;
  planId: string;
  files: GitHubCicdFile[];
}

export interface WorkflowPullRequestResult {
  number: number;
  url: string;
  branch: string;
}

const API_URL = 'https://api.github.com';

export function createGitHubCicdClient(
  token: string,
) {
  async function request<T>(
    path: string,
    method = 'GET',
    body?: unknown,
  ): Promise<T> {
    let response: Response;

    try {
      response = await fetch(`${API_URL}${path}`, {
        method,
        headers: {
          Accept: 'application/vnd.github+json',
          Authorization: `Bearer ${token}`,
          'X-GitHub-Api-Version': '2022-11-28',
          ...(body !== undefined
            ? { 'Content-Type': 'application/json' }
            : {}),
        },
        ...(body !== undefined
          ? { body: JSON.stringify(body) }
          : {}),
        signal: AbortSignal.timeout(30000),
      });
    } catch {
      throw new ConflictError(
        'GitHub API is unreachable',
      );
    }

    if (!response.ok) {
      throw new ConflictError(
        `GitHub API request failed (${response.status})`,
      );
    }

    if (response.status === 204) {
      return undefined as T;
    }

    return await response.json() as T;
  }

  async function createWorkflowPullRequest(
    input: CreateWorkflowPullRequestInput,
  ): Promise<WorkflowPullRequestResult> {
    const repoPath =
      `/repos/${encodeURIComponent(input.owner)}/${encodeURIComponent(input.repository)}`;

    const baseBranch = input.baseBranch;
    const branch = `deploymentplanner/plan-${input.planId}`;

    const baseRef = await request<GitHubRef>(
      `${repoPath}/git/ref/heads/${baseBranch.split('/').map(encodeURIComponent).join('/')}`,
    );

    await request(
      `${repoPath}/git/refs`,
      'POST',
      {
        ref: `refs/heads/${branch}`,
        sha: baseRef.object.sha,
      },
    );

    for (const file of input.files) {
      const filePath = file.path
        .split('/')
        .map(encodeURIComponent)
        .join('/');

      await request(
        `${repoPath}/contents/${filePath}`,
        'PUT',
        {
          message: `Adem: ci add ${file.path}`,
          content: Buffer.from(
            file.content,
            'utf8',
          ).toString('base64'),
          branch,
        },
      );
    }

    const pullRequest =
      await request<GitHubPullRequest>(
        `${repoPath}/pulls`,
        'POST',
        {
          title:
            `DeploymentPlanner CI/CD - Plan ${input.planId}`,
          head: branch,
          base: baseBranch,
          body: [
            'Generated by DeploymentPlanner AI.',
            '',
            'Review the Dockerfiles and GitHub Actions',
            'workflow before merging.',
            '',
            'The workflow builds and publishes Docker',
            'images to GitHub Container Registry.',
          ].join('\n'),
        },
      );

    return {
      number: pullRequest.number,
      url: pullRequest.html_url,
      branch,
    };
  }

  return {
    createWorkflowPullRequest,
  };
}

export type GitHubCicdClient =
  ReturnType<typeof createGitHubCicdClient>;
